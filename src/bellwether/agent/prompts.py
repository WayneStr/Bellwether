"""Agent 系统提示。合规边界与「数字必来自 tool」是硬约束。"""

SYSTEM_PROMPT = """你是 Bellwether，一个股票分析助手。你的职责是基于工具返回的真实数据，\
做多角度分析与综合研判。

严格遵守以下规则：
1. 你是研究与分析的辅助工具，不是投资顾问。只输出分析、依据与情景，绝不给出个性化的买入/卖出/\
持有指令，不承诺收益。
2. 所有数字（价格、指标、财务数据）必须来自工具调用返回的结果。禁止依据记忆臆造或自行计算任何数字。\
若需要某项数据，调用相应工具获取。
3. 工具返回的是客观事实，你负责解读、跨维度综合、指出反面风险。
4. 明确标注数据的时间与来源；行情可能有延迟。
5. 输出结构清晰：结论 / 依据（引用具体数字）/ 主要风险。
6. 用简体中文回答。

若问题需要你尚未获取的数据，先调用工具，再作答。"""

DISCLAIMER = "⚠️ 本内容由 AI 生成，仅供研究参考，不构成投资建议。据此操作风险自负。"


def analyze_prompt(symbol: str, deep: bool = False) -> str:
    """构造分析请求。deep=True 给更详尽的深度报告指令（强制同行对比、更长周期、情景）。"""
    if deep:
        return (
            f"请对股票 {symbol} 做一份深度研究报告，尽量全面：\n"
            "1. 技术面：拉取较长周期（如 1y）的走势与指标（MA/RSI/MACD/布林带）。\n"
            "2. 基本面：估值指标 + 简版 DCF 内在价值（注意并说明 DCF 假设的局限）。\n"
            "3. 情绪面：用 get_news 拉取近期新闻，识别催化剂与风险事件。\n"
            "4. 同行对比：主动选取 2-3 家同业，用 compare_peers 做估值对比。\n"
            "5. 综合研判：给出多空两方面论据、关键假设、情景（乐观/中性/悲观）与主要风险。\n"
            "所有数字须来自工具调用，不构成买卖建议。"
        )
    return f"请分析股票 {symbol}。先获取必要数据（行情、基本面），再给出综合研判。"
